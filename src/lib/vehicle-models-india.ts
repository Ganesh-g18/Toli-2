const compare=(a:string,b:string)=>a.localeCompare(b,'en',{sensitivity:'base',numeric:true});
export const vehicleModelsIndia:Readonly<Record<string,readonly string[]>> = Object.fromEntries(Object.entries(catalogue).map(([brand,models])=>[brand,[...new Set(models)].sort(compare)]));
export function modelsForBrand(brand:string):readonly string[] {
 const key=Object.keys(vehicleModelsIndia).find(key=>normalizeBrand(key)===normalizeBrand(brand));
 return key?vehicleModelsIndia[key]:[];
}
